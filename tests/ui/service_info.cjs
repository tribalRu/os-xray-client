const fs = require('fs'); const { JSDOM } = require('jsdom'); const assert = require('assert');
const s = fs.readFileSync(__dirname + '/../../src/opnsense/mvc/app/views/OPNsense/XrayClient/index.volt', 'utf8');
const a = s.indexOf('        function renderServiceInfo(info) {');
const b = s.indexOf('        function loadServiceInfo() {');
assert(a > 0 && b > a);
const dom = new JSDOM('<table><tr><td id="lbl_service_state"></td><td id="lbl_service_note"></td></tr></table>', { runScripts: 'outside-only' });
const w = dom.window;
w.eval(fs.readFileSync(__dirname + '/node_modules/jquery/dist/jquery.js', 'utf8'));
w.eval(s.slice(a, b));
const $ = w.$;
w.renderServiceInfo({ state: 'running', uptime_text: '3d 4h', auto_restarted: false });
assert.strictEqual($('#lbl_service_state').text(), 'Running, up 3d 4h');
assert.strictEqual($('#lbl_service_note').text(), '');
w.renderServiceInfo({ state: 'running', uptime_text: '12m', auto_restarted: true });
assert(/restarted automatically 12m ago/.test($('#lbl_service_note').text()));
assert($('#lbl_service_note').hasClass('text-warning'));
w.renderServiceInfo({ state: 'restarting' });
assert.strictEqual($('#lbl_service_state').text(), 'Restarting');
w.renderServiceInfo({ state: 'stopped' });
assert.strictEqual($('#lbl_service_state').text(), 'Stopped');
assert.strictEqual($('#lbl_service_note').text(), '');
assert(!$('#lbl_service_note').hasClass('text-warning'));
w.renderServiceInfo(null);
assert.strictEqual($('#lbl_service_state').text(), 'Unknown');
console.log('service info OK');
